"""Locked tests for crash-report redaction order and UTF-8 byte caps (issue #152, round 2).

These tests are the lock for the Qwen fix pass: do not edit this file to make them pass.
Fixes belong in src/crash_report.py only.

Rules the tests pin (all sizes are UTF-8 bytes, markers are appended after the cap):
- Redaction runs before truncation, so an identifier cut by a size cap never leaks partially.
- read_fatal() and log_tail() cap in bytes and never leave a split UTF-8 sequence.
- The exception message is bounded to MESSAGE_CAP bytes.
- report.json + app.log together stay under REPORT_CAP bytes (uncompressed).

No hardware, no real HOME: everything lives under tmp_path, identity lookups are patched.
"""

import getpass
import io
import json
import logging
import pwd
import socket
import zipfile
from unittest import mock

import pytest

import crash_report as cr

BUILD = {
    "base": "https://drop.invalid/reports",
    "token": "test-only-token",
    "version": "0.5.1",
    "commit": "abc1234",
}
CUT = "\n... [cut] ...\n"
REPORT_CAP = 512 * 1024  # report.json + app.log, uncompressed bytes
MESSAGE_CAP = 4096       # exception message bytes in report["message"]


@pytest.fixture
def isolated(tmp_path, monkeypatch):
    """Fake HOME, no login name in the environment, no passwd entry, fixed hostname, no upload."""
    home = tmp_path / "home"
    home.mkdir()
    monkeypatch.setenv("HOME", str(home))
    for var in ("USER", "LOGNAME", "LNAME", "USERNAME"):
        monkeypatch.delenv(var, raising=False)
    monkeypatch.setattr(pwd, "getpwuid", mock.Mock(side_effect=KeyError("no passwd entry")))
    monkeypatch.setattr(socket, "gethostname", lambda: "testhost-r2")
    monkeypatch.setattr(cr, "upload_report", mock.Mock(side_effect=AssertionError("no upload in r2 tests")))
    return home


def _make(tmp_path, log_text=lambda: ""):
    """A CrashReporter that never starts its worker: _report() is called directly."""
    state = tmp_path / "state"
    state.mkdir(exist_ok=True)
    return cr.CrashReporter(
        dict(BUILD), str(tmp_path / "settings.json"), state,
        logging.getLogger(f"test.crash.r2.{tmp_path.name}"), log_text=log_text,
    )


def _report_zip(reporter, exc, fatal):
    _name, data = reporter._report(exc, None, fatal)
    z = zipfile.ZipFile(io.BytesIO(data))
    report = json.loads(z.read("report.json"))
    log = z.read("app.log").decode("utf-8")
    return report, log, z


def _fatal(tmp_path, data: bytes) -> str:
    path = tmp_path / "fatal-desktop.log"
    path.write_bytes(data)
    return str(path)


def test_identifier_straddling_truncation_is_not_leaked_partially(isolated, tmp_path, monkeypatch):
    """A username cut by the fatal-log byte cap must not survive as a partial prefix ("qwx")."""
    monkeypatch.setattr(getpass, "getuser", lambda: "qwxzebra")
    cap = cr.MAX_FATAL_BYTES
    # The username starts 3 bytes before the cap, so a raw cut would keep "qwx".
    raw = b"x" * (cap - 4) + b" qwxzebra trailing words"
    report, log, _ = _report_zip(
        _make(tmp_path), cr.FatalError("Fatal Python error (previous run)"), _fatal(tmp_path, raw))
    text = json.dumps(report) + log
    assert "qwxzebra" not in text
    assert "qwx" not in text


def test_no_user_build_token_straddling_cut_is_redacted(isolated, tmp_path, monkeypatch):
    """No login name anywhere: the build token still must not leak partially, and the home path is redacted."""
    def no_login():
        raise OSError("no login name")

    monkeypatch.setattr(getpass, "getuser", no_login)
    cap = cr.MAX_FATAL_BYTES
    # The build token starts 6 bytes before the cap, so a raw cut would keep "test-o".
    raw = b"y" * (cap - 7) + b" test-only-token trailing words"
    reporter = _make(tmp_path)
    report, log, _ = _report_zip(reporter, cr.FatalError("Fatal Python error (previous run)"),
                                 _fatal(tmp_path, raw))
    text = json.dumps(report) + log
    assert "test-only-token" not in text
    assert "test-o" not in text

    home = str(isolated)
    report2, _, _ = _report_zip(reporter, ValueError(f"cannot open {home}/cfg.json"), None)
    assert home not in report2["message"]
    assert "~/cfg.json" in report2["message"]


def test_multibyte_cut_gives_valid_utf8_within_byte_cap(tmp_path):
    """read_fatal() on a file whose byte cap splits a 2-byte character: no U+FFFD, body within the byte cap."""
    out = cr.read_fatal(_fatal(tmp_path, b"a" + "é".encode() * 200_000))
    assert out.endswith(CUT)
    body = out.removesuffix(CUT)
    assert "�" not in out
    assert len(body.encode("utf-8")) <= cr.MAX_FATAL_BYTES


def test_read_fatal_raw_text_cap_counts_bytes():
    """A raw (non-path) fatal text of multi-byte characters is capped in bytes, not characters."""
    out = cr.read_fatal("é" * 200_000)
    assert out.endswith(CUT)
    body = out.removesuffix(CUT)
    assert len(body.encode("utf-8")) <= cr.MAX_FATAL_BYTES


def test_log_tail_line_cap_counts_utf8_bytes():
    """A multi-byte log line is cut at MAX_LOG_LINE_CHARS bytes plus the cut marker, not 2048 characters."""
    tail = cr.log_tail("é" * 3000 + "\n")
    line = tail.removesuffix("\n")
    assert line.endswith(" ... [cut]")
    assert len(line.encode("utf-8")) <= cr.MAX_LOG_LINE_CHARS + len(b" ... [cut]")


def test_huge_exception_message_is_bounded(isolated, tmp_path):
    """A multi-megabyte exception message is bounded in the report."""
    report, _, _ = _report_zip(_make(tmp_path), ValueError("m" * 2_000_000), None)
    assert len(report["message"].encode("utf-8")) <= MESSAGE_CAP


def test_whole_report_stays_under_byte_cap(isolated, tmp_path, monkeypatch):
    """Worst case: 256 KiB fatal traceback plus a full 500-line, ~1 MB log. report.json + app.log must fit REPORT_CAP."""
    monkeypatch.setattr(getpass, "getuser", lambda: "tester-r2")
    fatal = _fatal(tmp_path, b"Fatal crash line\n" + b"Z" * (300 * 1024))
    line = "INFO [main] test: " + "A" * 2000
    reporter = _make(tmp_path, log_text=lambda: "\n".join([line] * 500) + "\n")
    _report, _log, z = _report_zip(reporter, cr.FatalError("Fatal Python error (previous run)"), fatal)
    total = sum(z.getinfo(name).file_size for name in ("report.json", "app.log"))
    assert total <= REPORT_CAP
