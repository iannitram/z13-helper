"""Locked tests for the #123 reading-safety fix in src/goal_control.py.

Owner decisions these tests pin (do not edit this file to make code pass):
1. A reading is valid only if it is an int or float (not bool), finite and >= 0.
   Invalid readings behave exactly like None. decide() never raises for them.
2. Over-limit (valid apu_temp_c >= limit) is checked first for every goal except
   custom: shed one step and step fans toward FAN_MAX_PCT, regardless of dwell and
   regardless of missing goal readings. Reason "over APU temperature limit".
3. Goal "max" needs a valid apu_temp_c; otherwise hold with
   "no change: missing reading".
4. Other goals: an invalid goal reading -> "no change: missing reading".
"""

import pytest

import goal_control as g

CUR = g.Setpoints(spl_w=30, sppt_w=40, fppt_w=50, fan_pct=50)
HOT_SHED = g.Setpoints(spl_w=27, sppt_w=37, fppt_w=47, fan_pct=60)
NAN = float("nan")
INF = float("inf")
HOT = 96.0
MISSING = "no change: missing reading"

BAD = [NAN, INF, -1, True, "x"]
BAD_IDS = ["nan", "inf", "negative", "bool", "string"]

GOAL_CASES = [
    (g.Goal("quiet", 3000), "fan_rpm"),
    (g.Goal("comfort", 38), "comfort_temp_c"),
    (g.Goal("fps", 60), "fps"),
]


def run(goal, r, cur=CUR, state=g.State(), now=100.0, limits=g.Limits()):
    return g.decide(goal, r, cur, state, now, limits)


# --- decision 1 and 4: invalid goal readings are missing, never raise ---

@pytest.mark.parametrize("goal,field", GOAL_CASES, ids=["quiet", "comfort", "fps"])
@pytest.mark.parametrize("bad", BAD, ids=BAD_IDS)
def test_invalid_goal_reading_holds(goal, field, bad):
    d = run(goal, g.Readings(apu_temp_c=70, **{field: bad}))
    assert d.setpoints == CUR and not d.changed
    assert d.reason == MISSING


@pytest.mark.parametrize("bad", BAD, ids=BAD_IDS)
def test_custom_never_raises_on_bad_readings(bad):
    d = run(g.Goal("custom"), g.Readings(fan_rpm=bad, apu_temp_c=bad,
                                         comfort_temp_c=bad, fps=bad))
    assert d.setpoints == CUR and not d.changed


# --- decision 1: invalid apu_temp_c is missing, so it cannot shed ---

@pytest.mark.parametrize("goal,field", [
    (g.Goal("quiet", 3000), "fan_rpm"),
    (g.Goal("comfort", 38), "comfort_temp_c"),
    (g.Goal("fps", 60), "fps"),
], ids=["quiet", "comfort", "fps"])
@pytest.mark.parametrize("bad", BAD, ids=BAD_IDS)
def test_invalid_apu_is_not_hot(goal, field, bad):
    # The goal reading is in band, so the only thing that could move is the
    # over-limit check. An invalid apu_temp_c must not trigger it.
    target = {"quiet": 3000, "comfort": 38, "fps": 60}[goal.kind]
    d = run(goal, g.Readings(apu_temp_c=bad, **{field: target}))
    assert d.setpoints == CUR and not d.changed
    assert d.reason != "over APU temperature limit"


def test_apu_just_under_limit_is_not_hot():
    d = run(g.Goal("fps", 60), g.Readings(fps=60, apu_temp_c=94.9))
    assert not d.changed and d.reason == "within fps band"


# --- decision 3: max needs a valid apu_temp_c ---

@pytest.mark.parametrize("apu", [None, NAN, INF, -1, True, "x"],
                         ids=["none", "nan", "inf", "negative", "bool", "string"])
def test_max_holds_when_apu_missing_or_invalid(apu):
    d = run(g.Goal("max"), g.Readings(apu_temp_c=apu, fps=60, fan_rpm=3000,
                                      comfort_temp_c=38))
    assert d.setpoints == CUR and not d.changed
    assert d.reason == MISSING


# --- decision 2: over-limit sheds regardless of missing goal readings ---

@pytest.mark.parametrize("goal", [g.Goal("fps", 60), g.Goal("quiet", 3000),
                                  g.Goal("comfort", 38)], ids=["fps", "quiet", "comfort"])
@pytest.mark.parametrize("apu", [95.0, HOT])
def test_hot_sheds_when_goal_reading_missing(goal, apu):
    d = run(goal, g.Readings(apu_temp_c=apu))
    assert d.changed and d.setpoints == HOT_SHED
    assert d.reason == "over APU temperature limit"
    assert d.state.last_change_at == 100.0


@pytest.mark.parametrize("goal,field", GOAL_CASES, ids=["quiet", "comfort", "fps"])
@pytest.mark.parametrize("bad", BAD, ids=BAD_IDS)
def test_hot_sheds_when_goal_reading_invalid(goal, field, bad):
    d = run(goal, g.Readings(apu_temp_c=HOT, **{field: bad}))
    assert d.changed and d.setpoints == HOT_SHED
    assert d.reason == "over APU temperature limit"


@pytest.mark.parametrize("goal,r", [
    (g.Goal("fps", 60), g.Readings(fps=40, apu_temp_c=HOT)),
    (g.Goal("quiet", 3000), g.Readings(fan_rpm=4500, apu_temp_c=HOT)),
    (g.Goal("comfort", 38), g.Readings(comfort_temp_c=42, apu_temp_c=HOT)),
    (g.Goal("max"), g.Readings(apu_temp_c=HOT)),
], ids=["fps", "quiet", "comfort", "max"])
def test_hot_sheds_inside_dwell(goal, r):
    st = g.State(last_change_at=100.0)
    d = run(goal, r, CUR, st, 101.0)
    assert d.changed and d.setpoints == HOT_SHED
    assert d.reason == "over APU temperature limit"
    assert d.state.last_change_at == 101.0


# --- normal (not hot) changes still respect the dwell ---

@pytest.mark.parametrize("goal,r", [
    (g.Goal("fps", 60), g.Readings(fps=40, apu_temp_c=70)),
    (g.Goal("quiet", 3000), g.Readings(fan_rpm=4500, apu_temp_c=70)),
    (g.Goal("comfort", 38), g.Readings(comfort_temp_c=42)),
], ids=["fps", "quiet", "comfort"])
def test_normal_change_still_holds_in_dwell(goal, r):
    st = g.State(last_change_at=100.0)
    d = run(goal, r, CUR, st, 110.0)
    assert not d.changed and d.setpoints == CUR
    assert d.reason == "minimum dwell" and d.state == st
